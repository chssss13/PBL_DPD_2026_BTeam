"""Regenerate the C++ header from the exact Python integer endpoints."""
from pathlib import Path
import numpy as np
from activation_interp import SIGMOID, TANH

root = Path(__file__).resolve().parents[1]
header = ['// Generated by tools/generate_activation_interp.py. Integer Q3.13 endpoints.', '#pragma once', '#include "ap_int.h"', 'namespace activation_interp_tables {']
for name, a in [('sigmoid',SIGMOID),('tanh',TANH)]:
    delta = np.diff(a)
    assert len(a) == 513 and delta.min() >= 0 and delta.max() <= 128
    packed = ((a[:-1]&65535) | (delta<<16)).tolist()
    bits = 22 if name == 'sigmoid' else 24
    assert delta.max() < (1 << (bits-16))
    header += [f'static const ap_uint<{bits}> {name}[512] = {{']
    header += [', '.join(map(str,packed[i:i+16]))+',' for i in range(0,512,16)]
    header += ['};']
header += ['}']
(root/'src/activation_interp.h').write_text('\n'.join(header)+'\n',encoding='utf-8')
