"""Check the v4.7 layer-2 weight bypass on the v5-1.4 RTL."""
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path
import re
import shutil
import subprocess
import tempfile

root = Path(__file__).resolve().parent
reference = root.parent / "v5-1.4"
rtl = reference / "rtl"
loop = "ResGRU_Loop_LOOP_T_proc.v"
original = (rtl / loop).read_text()
entry = (rtl / "ResGRU_Block_entry_split_proc.v").read_text()
top = (rtl / "ResGRU.v").read_text()
probe = (reference / "probe.v").read_text()


def bypass(source):
    gates = ("ir", "iz", "in", "hn")
    mapping = {}
    paths = {}
    for gate in gates:
        for row in range(5):
            for column in range(5):
                weight = f"W_{gate}_1_{row}_{column}"
                aliases = re.findall(rf"assign (\w+) = \$signed\({weight}\);", entry)
                signal, = aliases or [weight]
                output, = re.findall(rf"(ap_return_\d+) = {signal};", entry)
                fifo, = re.findall(rf"\.din\(Block_entry_split_proc_U0_{output}\), \.dout\((\w+)\)", top)
                port, = re.findall(rf"\.(p_read\d+)\({fifo}\)", top)
                first, = re.findall(rf"(p_read_\w+) <= {port};", original)
                current = first
                chain = [first]
                for _ in range(3):
                    current, = re.findall(rf"(p_read_\w+) <= {current};", original)
                    chain.append(current)
                assert current.endswith("_pp0_iter3_reg")
                assert not re.search(rf"p_read_\w+ <= {current};", original)
                assert current not in mapping
                mapping[current] = first
                paths[weight] = dict(fifo=fifo, port=port, registers=chain)
    assert len(mapping) == 100
    for register, first in mapping.items():
        source, count = re.subn(rf"(?:(?<= = )|(?<=\()){register}(?=;|\))", first, source)
        assert count == 1, register
    return source, paths


def stress_probe():
    def vary(match):
        gate, row, column, raw = match.groups()
        index = ("ir", "iz", "in", "hn").index(gate) * 25 + 5 * int(row) + int(column)
        return f".W_{gate}_1_{row}_{column}((14'd{raw} + weight + 14'd{(index * 17) % 127}))"

    short = (probe.replace("accepted==120", "accepted==16")
             .replace("finished==120", "finished==16").replace("finished_push!=120", "finished_push!=16")
             .replace("!=15360", "!=2048"))
    varied, count = re.subn(r"\.W_(ir|iz|in|hn)_1_([0-4])_([0-4])\(14'd(\d+)\)", vary, short)
    assert count == 100
    return varied


def simulate(output_dir, name, source, bench, calls):
    work = output_dir / name
    work.mkdir(exist_ok=False)
    for path in [*rtl.glob("*.dat"), *(reference / name for name in ("iq.hex", "gate.hex"))]:
        shutil.copyfile(path, work / path.name)
    (work / loop).write_text(source)
    (work / "probe.v").write_text(bench)
    sources = [work / loop if path.name == loop else path for path in sorted(rtl.glob("*.v"))]
    with (work / "compile.log").open("w") as log:
        subprocess.run(["iverilog", "-g2012", "-s", "probe", "-o", "run.vvp", "probe.v", *sources],
                       cwd=work, stdout=log, stderr=subprocess.STDOUT, check=True)
    log_path = work / "run.log"
    with log_path.open("w") as log:
        subprocess.run(["vvp", "run.vvp"], cwd=work, stdout=log, stderr=subprocess.STDOUT, check=True)
    events = [line.split() for line in log_path.read_text().splitlines() if line.startswith(("WRITE ", "DONE "))]
    assert sum(event[0] == "DONE" for event in events) == calls
    writes = [(int(event[3]), int(event[4])) for event in events if event[0] == "WRITE"]
    assert len(writes) == calls * 128
    values = []
    for offset in range(0, len(writes), 128):
        block = sorted(writes[offset:offset + 128])
        assert [address for address, _ in block] == list(range(128))
        values.extend(value for _, value in block)
    return values, events


if __name__ == "__main__":
    changed, _ = bypass(original)
    released = (root / "rtl" / loop).read_text()
    assert released == changed, "Released RTL differs from the generated bypass"
    dynamic = stress_probe()
    with tempfile.TemporaryDirectory(prefix="resgru-v514-v47-") as output_dir, ThreadPoolExecutor(max_workers=2) as pool:
        fixed_job = pool.submit(simulate, Path(output_dir), "fixed_candidate", released, probe, 120)
        baseline_job = pool.submit(simulate, Path(output_dir), "dynamic_baseline", original, dynamic, 16)
        candidate_job = pool.submit(simulate, Path(output_dir), "dynamic_candidate", released, dynamic, 16)
        fixed, _ = fixed_job.result()
        golden = [int(value, 16) for value in (reference / "expected.hex").read_text().split()]
        assert len(golden) == 15360 and fixed == golden, "Fixed-weight RTL output mismatch"
        print("PASS: 100 bypasses, 7680 fixed-weight I/Q pairs match the v5-1.4 reference.", flush=True)
        baseline, baseline_events = baseline_job.result()
        candidate, candidate_events = candidate_job.result()
        assert baseline != golden[:len(baseline)], "Changing the weights must affect outputs"
        assert baseline_events == candidate_events, (
            next((a, b) for a, b in zip(baseline_events, candidate_events) if a != b)
            if len(baseline_events) == len(candidate_events) else "Event count mismatch"
        )
        assert baseline == candidate
        print("PASS: changing all 100 weights over 16 calls preserves I/Q bits and WRITE/DONE cycles.", flush=True)
